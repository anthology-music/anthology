def referenced(path: Path, *, tag_writes_allowed: bool = False) -> service.AudioFileInfo:
    return dataclasses.replace(
        audio(str(path)),
        format=AudioFormat.MP3,
        codec="mp3",
        bit_depth=None,
        bitrate_kbps=192,
        size_bytes=path.stat().st_size,
        declared_quality=QualityTier.LOSSY_HIGH,
        storage_mode=StorageMode.REFERENCED,
        tag_writes_allowed=tag_writes_allowed,
    )


def foreign_file(tmp_path: Path, name: str = "song.mp3") -> Path:
    """A file in a folder Anthology does not own (generated bytes, no real audio)."""
    path = tmp_path / "Music" / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(b"ID3" + bytes(range(256)) * 16)
    return path


async def referenced_album(
    session: AsyncSession, tmp_path: Path, names: list[str], *, tag_writes_allowed: bool = False
) -> list[Track]:
    """An album whose originals are referenced files in a foreign folder."""
    artist = await service.get_or_create_artist(session, "Nordlicht")
    release = await service.create_release(session, title="Polarnacht", album_artist=artist)
    return [
        await service.add_recording(
            session,
            release=release,
            title=name,
            artist=artist,
            duration_ms=200_000,
            track_number=number,
            audio=referenced(
                foreign_file(tmp_path, f"{name}.mp3"), tag_writes_allowed=tag_writes_allowed
            ),
        )
        for number, name in enumerate(names, start=1)
    ]


async def test_one_active_original_per_recording(app: FastAPI) -> None:
    async with app.state.sessionmaker() as session, session.begin():
        _, [track] = await album(session, "Nordlicht", "Polarnacht", ["Eisfeld"])
        recording_id = track.recording_id

    async with app.state.sessionmaker() as session:
        session.add(service._audio_file(recording_id, audio(), None))
        with pytest.raises(IntegrityError):
            await session.flush()

    async with app.state.sessionmaker() as session, session.begin():
        kept = service._audio_file(recording_id, audio(), None)
        kept.original_status = OriginalStatus.SUPERSEDED
        session.add(kept)  # a superseded file beside the active one is allowed

    async with app.state.sessionmaker() as session:
        files = await session.scalars(
            select(AudioFile.original_status).where(AudioFile.recording_id == recording_id)
        )
        assert sorted(files) == [OriginalStatus.ACTIVE, OriginalStatus.SUPERSEDED]


async def test_storage_columns_keep_their_check_constraints(app: FastAPI) -> None:
    async with app.state.sessionmaker() as session, session.begin():
        await album(session, "Nordlicht", "Polarnacht", ["Eisfeld"])

