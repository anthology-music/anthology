#!/usr/bin/env bash
#
# create-structure.sh – creates the Anthology monorepo folder structure.
#
# Usage:
#   ./create-structure.sh [target-directory]
#
# Default target: ./anthology
# The script is idempotent: existing folders and files are never overwritten.
# Empty folders get a .gitkeep so Git keeps them.

set -euo pipefail

TARGET="${1:-anthology}"

DIRS=(
  # --- OpenSpec: specs (source of truth, one folder per domain) ---
  "openspec/specs/library"
  "openspec/specs/sources"
  "openspec/specs/jobs"
  "openspec/specs/sync-protocol"
  "openspec/specs/transcoding"
  "openspec/specs/playback"
  "openspec/specs/users"
  "openspec/specs/works"
  "openspec/specs/publishers"
  "openspec/specs/sheet-music"
  "openspec/specs/video"
  "openspec/specs/library-import"
  "openspec/specs/quality-analysis"
  "openspec/specs/cd-import"
  # --- OpenSpec: changes ---
  "openspec/changes/archive"

  # --- Agent tooling (commands/skills are generated by `openspec init`) ---
  ".claude/commands/opsx"
  ".claude/skills"
  ".claude/agents"
  ".opencode/commands"
  ".opencode/skills"
  ".opencode/agents"

  # --- Documentation ---
  "docs/concept"
  "docs/architecture"
  "docs/adr"
  "docs/design"

  # --- Server (Python, FastAPI) – modules mirror the spec domains ---
  "server/anthology/library"
  "server/anthology/sources"
  "server/anthology/jobs"
  "server/anthology/sync"
  "server/anthology/transcoding"
  "server/anthology/playback"
  "server/anthology/users"
  "server/anthology/works"
  "server/anthology/publishers"
  "server/anthology/sheet_music"
  "server/anthology/video"
  "server/anthology/library_import"
  "server/anthology/quality_analysis"
  "server/anthology/cd_import"
  "server/anthology/api"
  "server/anthology/db"
  "server/anthology/fuse"
  "server/migrations"
  "server/tests"

  # --- Client (Vue 3 + Quasar: Web/PWA, Tauri, Capacitor) ---
  "client/src"
  "client/src-tauri"
  "client/src-capacitor"

  # --- Shared packages ---
  "packages/api-types"

  # --- Separate services with their own (copyleft) licenses, one container each ---
  "services/tagger"
  "services/source-tidal"
  "services/audiveris"

  # --- Deployment (Podman first: Quadlet; Compose for Podman/Docker) ---
  "deploy/quadlet"

  # --- Tools, CI ---
  "tools"
  ".github/workflows"
)

echo "Creating Anthology structure in: ${TARGET}"
mkdir -p "${TARGET}"

created=0
for dir in "${DIRS[@]}"; do
  path="${TARGET}/${dir}"
  if [[ ! -d "${path}" ]]; then
    mkdir -p "${path}"
    created=$((created + 1))
  fi
done

# Add .gitkeep to every folder that is still empty
gitkeeps=0
while IFS= read -r -d '' empty_dir; do
  touch "${empty_dir}/.gitkeep"
  gitkeeps=$((gitkeeps + 1))
done < <(find "${TARGET}" -type d -empty -not -path "*/.git/*" -print0)

echo "Done: ${created} folders created, ${gitkeeps} .gitkeep files added."
echo
echo "Next steps:"
echo "  1. Copy AGENTS.md, CLAUDE.md, openspec/config.yaml and the specs into ${TARGET}"
echo "     (or extract the scaffold archive there)."
echo "  2. cd ${TARGET} && git init"
echo "  3. npm install -g @fission-ai/openspec@latest"
echo "  4. openspec init   (select Claude Code and OpenCode)"
