// Regenerates src/openapi.ts and src/sync.ts from the server.
// Needs uv (server) and the dev dependencies of this package.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { compile } from 'json-schema-to-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const server = resolve(root, '../../server');
const header = '// Generated by packages/api-types/scripts/generate.mjs – do not edit.\n\n';

function serverJson(module) {
  const output = execFileSync('uv', ['run', '--project', server, 'python', '-m', module], {
    cwd: server,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  return JSON.parse(output);
}

// REST API (OpenAPI)
const openapi = serverJson('anthology.api.openapi');
const scratch = mkdtempSync(join(tmpdir(), 'anthology-api-types-'));
const openapiFile = join(scratch, 'openapi.json');
writeFileSync(openapiFile, JSON.stringify(openapi));
const ast = await openapiTS(new URL(`file://${openapiFile}`));
writeFileSync(join(root, 'src/openapi.ts'), header + astToString(ast));

// Sync protocol messages (JSON Schema): titles of single fields would become type
// aliases (Type1, Sub2, …), so only model titles are kept.
function stripFieldTitles(node) {
  if (Array.isArray(node)) return node.forEach(stripFieldTitles);
  if (node === null || typeof node !== 'object') return;
  if (node.properties) {
    for (const property of Object.values(node.properties)) delete property.title;
  }
  Object.values(node).forEach(stripFieldTitles);
}
const sync = serverJson('anthology.sync.messages');
stripFieldTitles(sync);
const syncTypes = await compile(sync, 'SyncProtocol', {
  bannerComment: '',
  additionalProperties: false,
  style: { singleQuote: true },
});
writeFileSync(
  join(root, 'src/sync.ts'),
  header + `export const PROTOCOL_VERSION = ${sync.protocol};\n\n` + syncTypes,
);

console.log('api-types generated:', readFileSync(join(root, 'src/sync.ts'), 'utf8').length, 'bytes');
